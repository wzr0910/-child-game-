/**
 * 模拟真实网络/推理延迟
 * 完全没有等待感反而会露馅，也不利于前端 loading 态的自测
 */
export function demoDelay(ms = 900): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}
